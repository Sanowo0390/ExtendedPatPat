package jp.mintymc.patpat.velocity;

import com.github.retrooper.packetevents.protocol.entity.data.EntityData;
import com.github.retrooper.packetevents.protocol.entity.data.EntityDataTypes;
import com.github.retrooper.packetevents.protocol.player.ClientVersion;
import com.github.retrooper.packetevents.util.Vector3d;
import com.github.retrooper.packetevents.util.Vector3f;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Base64;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;

/**
 * Resource-pack-free 1.21.9+ renderer using player-face object text components.
 *
 * Signed textures are generated by MineSkin ONCE per 8x8 tile and cached on disk.
 * Unlike block-glyph text, each object is an 8x8 native sprite. Each sprite row
 * gets its own billboard so the font's one-pixel line gap never appears.
 *
 * PacketEvents COMPONENT (raw JSON) is used deliberately. Velocity's installed
 * Adventure API does not necessarily support ObjectComponent 4.25 at runtime;
 * converting through an older Adventure serializer could erase player objects.
 */
final class HeadTileFrames {
    private static final int TILE=8;
    private final int resolution;
    private final Map<String,String[][]> bySkin=new HashMap<>();

    HeadTileFrames(Path directory,SkinCatalog catalog,int requestedResolution) {
        resolution=normalizeResolution(requestedResolution);
        for(String id:catalog.ids()){
            SkinCatalog.Skin skin=catalog.get(id);
            String[][] all=new String[skin.frames()][];
            boolean complete=true;
            for(int frame=0;frame<all.length;frame++){
                try{all[frame]=load(directory.resolve(id).resolve(frame+".properties"),resolution);}
                catch(IOException | IllegalArgumentException e){complete=false;break;}
            }
            if(complete)bySkin.put(id,all);
        }
    }

    static int normalizeResolution(int value){
        return value==16 || value==24 || value==32 ? value:24;
    }
    int resolution(){return resolution;}
    int rows(){return resolution/TILE;}

    static boolean supported(ClientVersion version){
        return version!=null && !version.isOlderThan(ClientVersion.V_1_21_9);
    }
    boolean ready(SkinCatalog.Skin skin){return bySkin.containsKey(skin.id());}
    int readyCount(){return bySkin.size();}
    String row(SkinCatalog.Skin skin,int frame,int row){
        return bySkin.get(skin.id())[frame][row];
    }

    private static String[] load(Path path,int resolution) throws IOException {
        Properties p=new Properties();
        try(InputStream in=Files.newInputStream(path)){p.load(in);}
        if(Integer.parseInt(p.getProperty("resolution","0"))!=resolution)
            throw new IOException("Tile resolution mismatch");
        int count=resolution/TILE;
        String[] rows=new String[count];
        for(int y=0;y<count;y++){
            StringBuilder json=new StringBuilder("{\"text\":\"\",\"extra\":[");
            for(int x=0;x<count;x++){
                if(x>0)json.append(',');
                String token=p.getProperty("tile."+y+"."+x,"");
                if(token.isBlank()){
                    // Native 8px head object and two default-font 4px spaces
                    // have the same horizontal advance; no braille dots.
                    json.append("{\"text\":\"  \"}");
                    continue;
                }
                String[] parts=token.split(";",2);
                String value=checkedBase64(parts[0],8192);
                String signature=parts.length==2 && !parts[1].isEmpty()
                    ? checkedBase64(parts[1],2048):"";
                json.append("{\"type\":\"object\",\"object\":\"player\",\"hat\":false,")
                    .append("\"player\":{\"properties\":[{\"name\":\"textures\",\"value\":\"")
                    .append(value).append('\"');
                if(!signature.isEmpty())
                    json.append(",\"signature\":\"").append(signature).append('\"');
                json.append("}]}}");
            }
            rows[y]=json.append("]}").toString();
        }
        return rows;
    }

    static String checkedBase64(String input,int maxChars) throws IOException {
        if(input.isBlank() || input.length()>maxChars)
            throw new IOException("Invalid texture token length");
        try{
            Base64.getDecoder().decode(input);
        }catch(IllegalArgumentException e){
            throw new IOException("Invalid texture token Base64",e);
        }
        return input;
    }

    /** Each row is exactly 8/N of the image's world size and is independently billboarded. */
    static Vector3d position(Vector3d anchor,double imageSize,double down,int row,int rows) {
        return new Vector3d(anchor.getX(),
            anchor.getY()+imageSize*0.5-(row+1)*imageSize/rows+down,
            anchor.getZ());
    }

    /** JSON is already validated before entering a PacketEvents TEXT_DISPLAY packet. */
    @SuppressWarnings("deprecation")
    static EntityData<String> textMetadata(String json) {
        return new EntityData<>(23,EntityDataTypes.COMPONENT,json);
    }

    static List<EntityData<?>> spawnMetadata(String json,double imageSize,int resolution){
        float unit=(float)(imageSize*40/resolution);
        List<EntityData<?>> data=new ArrayList<>();
        data.add(new EntityData<>(12,EntityDataTypes.VECTOR3F,new Vector3f(unit,unit,1f)));
        data.add(new EntityData<>(15,EntityDataTypes.BYTE,(byte)3)); // CENTER billboard
        data.add(new EntityData<>(17,EntityDataTypes.FLOAT,4f)); // view range
        data.add(textMetadata(json));
        data.add(new EntityData<>(24,EntityDataTypes.INT,1024)); // no wrapping
        data.add(new EntityData<>(25,EntityDataTypes.INT,0)); // transparent backdrop
        data.add(new EntityData<>(26,EntityDataTypes.BYTE,(byte)-1)); // default opacity
        data.add(new EntityData<>(27,EntityDataTypes.BYTE,(byte)0)); // no shadow
        return data;
    }
}
